"""bevotron: info | data | tokenizer | prepare | sweep | run | eval | sample | judge | compare."""

from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
from pathlib import Path

from bevotron.config import RunConfig
from bevotron.eval.memory import memory
from bevotron.sweep import Run, load_sweep

RUNS = Path("runs")
RESULTS = Path("results")
BASELINE = Path("configs/baseline.yaml")


def _git_sha() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    except Exception:
        return "unknown"


def _write_run(run: Run) -> Path:
    """Create runs/<id>/ with the full config and provenance; idempotent."""
    folder = RUNS / run.run_id
    folder.mkdir(parents=True, exist_ok=True)
    run.config.save(folder / "config.yaml")
    (folder / "run.json").write_text(
        json.dumps(
            {
                "run_id": run.run_id,
                "training_key": run.config.training_key(),
                "ablation": run.ablation,
                "label": run.label,
                "overrides": run.overrides,
                "git_sha": _git_sha(),
                "non_embedding_params": run.config.non_embedding_params(),
                "total_params": run.config.total_params(),
                "memory_mb": memory(run.config).total_mb,
            },
            indent=2,
        )
    )
    return folder


def cmd_info(args: argparse.Namespace) -> None:
    config = RunConfig.load(args.config)
    mem = memory(config)
    m = config.model
    print(f"run id            {config.run_id()}")
    print(f"preset            {m.preset}  ({m.norm}, {m.pos_encoding}, {m.mlp_act})")
    print(
        f"shape             {m.n_layer} layers x {m.d_model} wide, {m.n_head} heads "
        f"({m.n_kv_head} kv), MLP {m.mlp_ratio}x, context {m.context_len}"
    )
    print(
        f"params            {config.non_embedding_params() / 1e6:.2f}M non-embedding, "
        f"{config.total_params() / 1e6:.2f}M total (vocab {config.tokenizer.vocab_size})"
    )
    print(
        f"train             {config.train.total_tokens / 1e6:.0f}M tokens, "
        f"{config.train.steps:,} steps of {config.train.batch_tokens:,}"
    )
    print(
        f"memory ({config.quant.scheme:<7}) {mem.weight_bytes / 1e6:.1f} MB weights + "
        f"{mem.kv_cache_bytes / 1e6:.1f} MB KV cache = {mem.total_mb:.1f} MB"
    )


def cmd_sweep(args: argparse.Namespace) -> None:
    runs = load_sweep(args.ablation, args.baseline)
    print(f"{runs[0].ablation}: {len(runs)} runs (incl. baseline)")
    for run in runs:
        c = run.config
        line = (
            f"  {run.run_id}  {run.label:<40} {c.non_embedding_params() / 1e6:6.1f}M params  "
            f"{c.train.total_tokens / 1e6:5.0f}M tok  {memory(c).total_mb:5.1f} MB"
        )
        print(line)
        if args.write:
            _write_run(run)
    if args.write:
        print(f"wrote {len(runs)} run folders under {RUNS}/")


def cmd_run(args: argparse.Namespace) -> None:
    config = RunConfig.load(args.config)
    folder = _write_run(Run(args.ablation, {}, config))
    print(f"run folder: {folder}")
    from bevotron.train.loop import train  # imports torch

    result = train(config, folder, resume=args.resume)
    print(
        f"done: val loss {result['val_loss']:.4f}  bpb {result['bpb']:.4f}  "
        f"({result['scheme']}, {result['memory_mb']:.1f} MB)"
    )


def cmd_eval(args: argparse.Namespace) -> None:
    folder = RUNS / args.run_id
    config = RunConfig.load(folder / "config.yaml")
    from bevotron.eval.quality import evaluate_run  # imports torch
    from bevotron.train.loop import pick_device

    result = evaluate_run(config, folder, device=pick_device(args.device))
    (folder / "eval.json").write_text(json.dumps(result, indent=2))
    print(json.dumps(result, indent=2))


def cmd_sample(args: argparse.Namespace) -> None:
    """Print stories generated by a run's checkpoint (full precision unless --quant)."""
    import torch

    from bevotron.data.prepare import resolve_tokenizer_path
    from bevotron.models import Bevo
    from bevotron.quant.ptq import apply_ptq
    from bevotron.tokenizer.bpe import BPETokenizer
    from bevotron.train.loop import pick_device

    folder = RUNS / args.run_id
    config = RunConfig.load(folder / "config.yaml")
    device = pick_device(args.device)
    tok = BPETokenizer.load(resolve_tokenizer_path(config))
    model = Bevo(config).to(device)
    model.load_state_dict(torch.load(folder / "ckpt.pt", map_location=device)["model"])
    if args.quant and config.quant.scheme != "none":
        apply_ptq(model, config.quant.scheme)
    model.eval()
    torch.manual_seed(args.seed)
    prompt = torch.tensor([tok.encode(args.prompt)], device=device)
    for i in range(args.n):
        out = model.generate(prompt, args.max_new_tokens, temperature=args.temperature, top_k=50)
        ids = out[0].tolist()
        if tok.eos_token_id in ids[prompt.size(1) :]:
            ids = ids[: prompt.size(1) + ids[prompt.size(1) :].index(tok.eos_token_id)]
        print(f"--- sample {i + 1} ---")
        print(tok.decode(ids))
        print()


def cmd_judge(args: argparse.Namespace) -> None:
    folder = RUNS / args.run_id
    config = RunConfig.load(folder / "config.yaml")
    if args.samples:
        config.eval.judge_samples = args.samples
    from bevotron.eval.judge import judge_run  # imports torch and anthropic
    from bevotron.train.loop import pick_device

    print(json.dumps(judge_run(config, folder, device=pick_device(args.device)), indent=2))


def cmd_prepare(args: argparse.Namespace) -> None:
    """Tokenize the dataset for a config (run does this automatically; useful before sweeps)."""
    from bevotron.data.prepare import prepare

    meta = prepare(RunConfig.load(args.config), workers=args.workers, force=args.force)
    print(
        f"{meta.dataset} @ vocab {meta.vocab_size}: {meta.train_tokens:,} train tokens, "
        f"{meta.val_tokens:,} val tokens, {meta.val_bytes:,} val bytes"
    )


def cmd_compare(args: argparse.Namespace) -> None:
    """Collect runs/<id>/eval.json for one ablation into results/<ablation>.csv."""
    rows = []
    for run_json in sorted(RUNS.glob("*/run.json")):
        meta = json.loads(run_json.read_text())
        if meta["ablation"] != args.ablation:
            continue
        evaluation = run_json.with_name("eval.json")
        result = json.loads(evaluation.read_text()) if evaluation.exists() else {}
        rows.append({**meta, **result})
    if not rows:
        sys.exit(
            f"no runs found for ablation {args.ablation!r}; run `bevotron sweep --write` first"
        )
    baseline = next((r for r in rows if r["label"] == "baseline"), None)
    for row in rows:
        for metric in ("perplexity", "bpb", "judge_mean"):
            if baseline and metric in row and metric in baseline:
                row[f"delta_{metric}"] = row[metric] - baseline[metric]
    RESULTS.mkdir(exist_ok=True)
    out = RESULTS / f"{args.ablation}.csv"
    keys = sorted({k for r in rows for k in r} - {"overrides"})
    with open(out, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        writer.writerows({k: r.get(k, "") for k in keys} for r in rows)
    print(f"wrote {out} ({len(rows)} runs)")


def cmd_data(args: argparse.Namespace) -> None:
    """Write a dataset split to one UTF-8 text file (stories separated by <|endoftext|>),
    the input `bevotron tokenizer train` expects."""
    from bevotron.data.prepare import export_text

    out, n = export_text(args.dataset, args.split, Path(args.output), limit=args.limit)
    print(f"wrote {n:,} documents to {out}")


def cmd_tokenizer(args: argparse.Namespace) -> None:
    from bevotron.tokenizer.bpe import BPETokenizer, train_bpe

    if args.tokenizer_cmd == "train":
        vocab, merges = train_bpe(args.input, args.vocab_size, progress=print)
        tok = BPETokenizer(vocab, merges)
        tok.save(args.output)
        print(f"saved {tok.vocab_size:,} tokens to {args.output}")
    else:
        tok = BPETokenizer.load(args.input)
        for size in args.sizes:
            out = Path(args.output_dir) / f"tokenizer_{size // 1000}k.json"
            tok.truncate(size).save(out)
            print(f"saved {size:,} tokens to {out}")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="bevotron", description=__doc__)
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("info", help="print shape, params, steps and memory for a config")
    p.add_argument("config", nargs="?", default=BASELINE)
    p.set_defaults(func=cmd_info)

    p = sub.add_parser("sweep", help="expand an ablation file into runs")
    p.add_argument("ablation")
    p.add_argument("--baseline", default=BASELINE)
    p.add_argument("--write", action="store_true", help="create runs/<id>/ folders")
    p.set_defaults(func=cmd_sweep)

    p = sub.add_parser("run", help="train one config")
    p.add_argument("config")
    p.add_argument("--ablation", default="manual", help="ablation name recorded in run.json")
    p.add_argument("--resume", action="store_true", help="continue from runs/<id>/ckpt.pt")
    p.set_defaults(func=cmd_run)

    p = sub.add_parser(
        "eval", help="re-evaluate a run's checkpoint (full precision + its quant scheme)"
    )
    p.add_argument("run_id")
    p.add_argument("--device", default="auto")
    p.set_defaults(func=cmd_eval)

    p = sub.add_parser("sample", help="print stories generated by a run's checkpoint")
    p.add_argument("run_id")
    p.add_argument("--prompt", default="Once upon a time")
    p.add_argument("-n", type=int, default=3)
    p.add_argument("--max-new-tokens", type=int, default=200)
    p.add_argument("--temperature", type=float, default=0.7)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--quant", action="store_true", help="apply the run's PTQ scheme first")
    p.add_argument("--device", default="auto")
    p.set_defaults(func=cmd_sample)

    p = sub.add_parser("judge", help="generate stories from a run and grade them with an LLM judge")
    p.add_argument("run_id")
    p.add_argument("--samples", type=int, default=None, help="override eval.judge_samples")
    p.add_argument("--device", default="auto")
    p.set_defaults(func=cmd_judge)

    p = sub.add_parser("prepare", help="tokenize the dataset for a config (cached per tokenizer)")
    p.add_argument("config", nargs="?", default=BASELINE)
    p.add_argument("--workers", type=int, default=8)
    p.add_argument("--force", action="store_true")
    p.set_defaults(func=cmd_prepare)

    p = sub.add_parser("compare", help="write results/<ablation>.csv against the baseline")
    p.add_argument("ablation")
    p.set_defaults(func=cmd_compare)

    p = sub.add_parser("data", help="export a dataset split as text for tokenizer training")
    p.add_argument("export", nargs="?", default="export")
    p.add_argument("--dataset", default="tinystories")
    p.add_argument("--split", default="train")
    p.add_argument("--output", default="data/tinystories/train.txt")
    p.add_argument("--limit", type=int, default=None, help="first N documents only")
    p.set_defaults(func=cmd_data)

    p = sub.add_parser("tokenizer", help="train or truncate the BPE tokenizer")
    tsub = p.add_subparsers(dest="tokenizer_cmd", required=True)
    t = tsub.add_parser("train")
    t.add_argument("--input", default="data/tinystories/train.txt")
    t.add_argument("--vocab-size", type=int, default=50000)
    t.add_argument("--output", default="artifacts/tokenizer/tokenizer_50k.json")
    t = tsub.add_parser("truncate")
    t.add_argument("--input", required=True)
    t.add_argument("--sizes", type=int, nargs="+", required=True)
    t.add_argument("--output-dir", default="artifacts/tokenizer")
    p.set_defaults(func=cmd_tokenizer)

    args = parser.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
